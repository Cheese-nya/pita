export function preference(k: string, fallback: string) {
  try {
    return localStorage.getItem("pita." + k) || fallback;
  } catch {
    return fallback;
  }
}
export function remember(k: string, v: string) {
  try {
    localStorage.setItem("pita." + k, v);
  } catch {
    /* Session preferences still apply. */
  }
}
const dict = (index: number) =>
  Object.fromEntries(Object.entries(messages).map(([k, v]) => [k, v[index]]));
i18n.use(initReactI18next).init({
  lng: preference("language", "zh-CN"),
  fallbackLng: "en",
  keySeparator: false,
  nsSeparator: false,
  parseMissingKeyHandler(key) {
    if (key.startsWith("custom:")) {
      try {
        const raw = localStorage.getItem("pita.settings.v1");
        if (raw) {
          const parsed = JSON.parse(raw) as {
            customHarnesses?: { id: string; name: string }[];
          };
          const found = parsed.customHarnesses?.find((h) => h.id === key);
          if (found?.name) return found.name;
        }
      } catch {
        /* ignore storage read errors */
      }
      return key.slice("custom:".length);
    }
    return key;
  },
  resources: {
    en: { translation: dict(1) },
    "zh-CN": { translation: dict(0) },
  },
  interpolation: { escapeValue: false },
});
document.documentElement.lang = i18n.language;
i18n.on("languageChanged", (l) => {
  document.documentElement.lang = l;
  remember("language", l);
});
